export function translateText(value, locale) {
    if (locale !== 'kk' || typeof value !== 'string') return value;
    if (kazakh[value]) return kazakh[value];
    if (/^Конкурс (ППС|АУП) #\d+$/.test(value)) return value.replace('Конкурс ППС', 'ОПҚ конкурсы').replace('Конкурс АУП', 'ӘБП конкурсы');
    if (/^Заявка №\d+$/.test(value)) return value.replace('Заявка', 'Өтінім');
    if (/^.+: заявка №\d+$/.test(value)) {
        const [title, id] = value.split(': заявка №');
        return `${translateText(title, locale)}: өтінім №${id}`;
    }
    if (/^Кадровая заявка №\d+$/.test(value)) return value.replace('Кадровая заявка', 'Кадрлық өтінім');
    if (/^Взять на [13] (год|года)$/.test(value)) return `${value.match(/[13]/)[0]} жылға қабылдау`;
    if (value.endsWith(': все')) return translateText(value.slice(0, -5), locale) + ': барлығы';
    if (value.endsWith(': архив')) return translateText(value.slice(0, -7), locale) + ': мұрағат';
    return value;
}

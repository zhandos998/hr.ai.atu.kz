const interpolate = (text, params) => Object.entries(params).reduce(
  (result, [key, value]) => result.replace(new RegExp(`\\{${key}\\}`, 'g'), value),
  text,
);

export const setLocale = (newLocale) => {
  locale.value = supportedLocales.includes(newLocale) ? newLocale : defaultLocale;

  if (typeof window !== 'undefined') {
    window.localStorage.setItem(storageKey, locale.value);
  }
};

export const t = (key, params = {}) => {
  const text = messages[locale.value]?.[key] || messages[defaultLocale]?.[key] || key;
  return interpolate(text, params);
};

export const roleLabel = (role) => t(`role.${role || 'user'}`);

export const useI18n = () => ({
  locale,
  setLocale,
  t,
  roleLabel,
});
